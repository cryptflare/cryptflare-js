#!/usr/bin/env node
// Regenerates packages/sdk/typescript/src/core/error-codes.ts from the
// ERRORS registry in packages/shared/src/constants/errors.ts.
//
// The SDK ships standalone (no runtime dependency on @cryptflare/shared), so
// the registry is copied in rather than imported. `tests/core/error-codes.test.ts`
// fails when the copy drifts from shared, pointing back at this script.
//
// Usage: pnpm --filter @cryptflare/sdk gen:errors

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format } from 'node:util'

/** Progress line on stdout. */
const log = (...parts) => {
  process.stdout.write(`${format(...parts)}\n`)
}

const here = dirname(fileURLToPath(import.meta.url))
const SDK_ROOT = resolve(here, '..')
const SHARED_ERRORS = resolve(SDK_ROOT, '../../shared/src/constants/errors.ts')
const OUT_FILE = resolve(SDK_ROOT, 'src/core/error-codes.ts')

const text = readFileSync(SHARED_ERRORS, 'utf-8')
const lines = []
for (const raw of text.split('\n')) {
  const line = raw.trim()
  const comment = line.match(/^\/\/\s*(.+?)\s*$/)
  if (comment) {
    lines.push(`  // ${comment[1]}`)
    continue
  }
  const entry = line.match(/^([A-Z][A-Z0-9_]*):\s*'([^']+)',?$/)
  if (entry && entry[1] === entry[2]) lines.push(`  ${entry[1]}: '${entry[2]}',`)
}

const out = [
  '// GENERATED by scripts/gen-error-codes.mjs from packages/shared/src/constants/errors.ts.',
  '// Do not edit by hand. Run `pnpm --filter @cryptflare/sdk gen:errors` after changing shared.',
  '',
  '/** Every error code the CryptFlare API and MCP server can emit. */',
  'export const ERRORS = {',
  ...lines,
  '} as const;',
  '',
  '/** Union of every value in {@link ERRORS}. */',
  'export type ErrorCode = (typeof ERRORS)[keyof typeof ERRORS];',
  '',
].join('\n')

writeFileSync(OUT_FILE, out)
log(`[gen-error-codes] wrote ${OUT_FILE}`)
